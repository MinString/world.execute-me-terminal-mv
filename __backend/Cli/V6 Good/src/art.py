def blit_center(cv, art, y, fg=None, cx=None, map_fg=None):
    w = max(sw(l) for l in art) if art else 0
    x = (cv.w // 2 if cx is None else cx) - w // 2
    cv.blit(art, x, y, fg=fg, map_fg=map_fg)
    return y + len(art)


