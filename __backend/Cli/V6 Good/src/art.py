def banner_lines(text, scale=1, gap=1):
    """Render text with the block font.  Returns list of strings."""
    letters = [FONT.get(c.upper(), FONT[" "]) for c in text]
    rows = []
    for r in range(5):
        parts = []
        for li, L in enumerate(letters):
            parts.append(L[r])
            if li < len(letters) - 1:
                parts.append(" " * gap)
        line = "".join(parts)
        if scale > 1:
            line = "".join(c * scale for c in line)
        for _ in range(scale):
            rows.append(line)
    return rows


def banner_width(text, scale=1, gap=1):
    letters = [FONT.get(c.upper(), FONT[" "]) for c in text]
    w = 0
    for li, L in enumerate(letters):
        w += sw(L[0])
        if li < len(letters) - 1:
            w += gap
    return w * scale


