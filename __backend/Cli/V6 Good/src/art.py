def scale2(lines):
    """Double the size of block art (each cell rendered as 2x2)."""
    from renderer import sw
    maxw = max(sw(l) for l in lines) if lines else 0
    out = []
    for line in lines:
        pad = maxw - sw(line)
        if pad > 0:
            line = " " * (pad // 2) + line + " " * (pad - pad // 2)
        row = "".join(_EXPAND.get(c, c + c) for c in line)
        out.append(row)
        out.append(row)
    return out
